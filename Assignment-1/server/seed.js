async function ensureDevelopmentUsers() {
  let createdCount = 0;
  for (const userData of developmentUsers) {
    const existingUser = await User.findOne({ email: userData.email });
    if (existingUser) continue;
    await User.create(createDevelopmentUserData(userData));
    createdCount += 1;
  }
  return createdCount;
}

function createDevelopmentUserData(userData, environment = process.env) {
  const password = environment[userData.passwordEnv];
  if (typeof password !== 'string' || password.length < 6) {
    throw new Error(`${userData.passwordEnv} must be set to at least 6 characters before creating this development account.`);
  }

  const { passwordEnv, ...accountData } = userData;
  return { ...accountData, passwordHash: password };
}

