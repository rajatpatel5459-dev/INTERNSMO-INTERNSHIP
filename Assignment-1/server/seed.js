function readMp3Frame(buffer, offset) {
  if (buffer[offset] !== 0xff || (buffer[offset + 1] & 0xe0) !== 0xe0) return null;

  const versionBits = (buffer[offset + 1] >> 3) & 3;
  const layerBits = (buffer[offset + 1] >> 1) & 3;
  const bitrateIndex = (buffer[offset + 2] >> 4) & 15;
  const sampleRateIndex = (buffer[offset + 2] >> 2) & 3;
  if (versionBits === 1 || layerBits === 0 || bitrateIndex === 0 || bitrateIndex === 15 || sampleRateIndex === 3) {
    return null;
  }

  const version = versionBits === 3 ? 1 : 2;
  const layer = 4 - layerBits;
  const baseSampleRate = [44100, 48000, 32000][sampleRateIndex];
  const sampleRate = baseSampleRate / (versionBits === 3 ? 1 : versionBits === 2 ? 2 : 4);
  const bitrate = mpegBitrates[version][layer - 1][bitrateIndex] * 1000;
  const padding = (buffer[offset + 2] >> 1) & 1;
  const frameLength = layer === 1
    ? Math.floor((12 * bitrate) / sampleRate + padding) * 4
    : Math.floor(((layer === 3 && versionBits !== 3 ? 72 : 144) * bitrate) / sampleRate + padding);
  const samplesPerFrame = layer === 1 ? 384 : layer === 3 && versionBits !== 3 ? 576 : 1152;

  return {
    frameLength,
    durationSeconds: samplesPerFrame / sampleRate,
    stream: `${versionBits}-${layerBits}-${sampleRate}`,
  };
}

function getMp3DurationSeconds(buffer) {
  let start = 0;
  if (buffer.toString('ascii', 0, 3) === 'ID3') {
    const tagSize = ((buffer[6] & 0x7f) << 21)
      | ((buffer[7] & 0x7f) << 14)
      | ((buffer[8] & 0x7f) << 7)
      | (buffer[9] & 0x7f);
    start = 10 + tagSize;
  }

  let firstFrame;
  let firstOffset = start;
  for (let offset = start; offset + 8 < buffer.length; offset += 1) {
    const frame = readMp3Frame(buffer, offset);
    if (!frame || offset + frame.frameLength + 4 > buffer.length) continue;
    const nextFrame = readMp3Frame(buffer, offset + frame.frameLength);
    if (nextFrame && nextFrame.stream === frame.stream) {
      firstFrame = frame;
      firstOffset = offset;
      break;
    }
  }
  if (!firstFrame) throw new Error('Audio asset does not contain a valid MP3 frame stream.');

  let durationSeconds = 0;
  let offset = firstOffset;
  let frame = firstFrame;
  while (frame && frame.stream === firstFrame.stream && offset + frame.frameLength <= buffer.length) {
    durationSeconds += frame.durationSeconds;
    offset += frame.frameLength;
    frame = readMp3Frame(buffer, offset);
  }
  return Math.round(durationSeconds);
}

function readMp4DurationSeconds(buffer) {
  let moovStart = -1;
  let moovEnd = -1;
  for (let offset = 0; offset + 8 <= buffer.length;) {
    let size = buffer.readUInt32BE(offset);
    const type = buffer.toString('ascii', offset + 4, offset + 8);
    let headerSize = 8;
    if (size === 1) {
      if (offset + 16 > buffer.length) break;
      size = Number(buffer.readBigUInt64BE(offset + 8));
      headerSize = 16;
    } else if (size === 0) {
      size = buffer.length - offset;
    }
    if (size < headerSize || offset + size > buffer.length) break;
    if (type === 'moov') {
      moovStart = offset + headerSize;
      moovEnd = offset + size;
      break;
    }
    offset += size;
  }
  if (moovStart < 0) throw new Error('M4A asset is missing its movie metadata.');

  for (let offset = moovStart; offset + 8 <= moovEnd;) {
    let size = buffer.readUInt32BE(offset);
    const type = buffer.toString('ascii', offset + 4, offset + 8);
    let headerSize = 8;
    if (size === 1) {
      if (offset + 16 > moovEnd) break;
      size = Number(buffer.readBigUInt64BE(offset + 8));
      headerSize = 16;
    } else if (size === 0) {
      size = moovEnd - offset;
    }
    if (size < headerSize || offset + size > moovEnd) break;
    if (type === 'mvhd') {
      const payload = offset + headerSize;
      const version = buffer[payload];
      const timescaleOffset = payload + (version === 1 ? 20 : 12);
      const durationOffset = payload + (version === 1 ? 24 : 16);
      const timescale = buffer.readUInt32BE(timescaleOffset);
      const duration = version === 1
        ? Number(buffer.readBigUInt64BE(durationOffset))
        : buffer.readUInt32BE(durationOffset);
      if (!timescale) break;
      return Math.round(duration / timescale);
    }
    offset += size;
  }
  throw new Error('M4A asset is missing valid duration metadata.');
}

function readWavDurationSeconds(buffer) {
  if (buffer.toString('ascii', 0, 4) !== 'RIFF' || buffer.toString('ascii', 8, 12) !== 'WAVE') {
    throw new Error('Audio asset is not a valid WAV file.');
  }

  const byteRate = buffer.readUInt32LE(28);
  const dataOffset = buffer.indexOf('data', 12, 'ascii');
  if (!byteRate || dataOffset < 0 || dataOffset + 8 > buffer.length) {
    throw new Error('WAV asset is missing valid format or data metadata.');
  }
  const dataLength = Math.min(buffer.readUInt32LE(dataOffset + 4), buffer.length - dataOffset - 8);
  return Math.round(dataLength / byteRate);
}

function loadAssetTracks() {
  const assetDirectory = path.resolve(__dirname, '..', 'assets');

  return assetTrackDefinitions.map((definition) => {
    const audioSourcePath = path.join(assetDirectory, 'tracks', definition.audioFile);
    const coverSourcePath = path.join(assetDirectory, 'covers', definition.coverFile);
    const audioBuffer = fs.readFileSync(audioSourcePath);
    const coverBuffer = fs.readFileSync(coverSourcePath);
    if (!coverBuffer.subarray(0, 8).equals(Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]))) {
      throw new Error(`Cover asset is not a valid PNG: ${definition.coverFile}`);
    }

    const audioFormat = 'wav';
    const durationSeconds = readWavDurationSeconds(audioBuffer);
    if (!Number.isFinite(durationSeconds) || durationSeconds < 1) {
      throw new Error(`Audio asset has an invalid duration: ${definition.audioFile}`);
    }

    const audioFileName = `seed-${definition.slug}.${audioFormat}`;
    const coverFileName = `seed-${definition.slug}.png`;
    const trackData = {
      title: definition.title,
      artist: definition.artist,
      album: definition.album,
      genre: definition.genre,
      durationSeconds,
      audioAssetUrl: `/uploads/tracks/${audioFileName}`,
      coverImageUrl: `/uploads/tracks/${coverFileName}`,
      acoustic: definition.acoustic,
      timeline: definition.timeline,
    };
    const timelineError = validateTrackTimeline(trackData.timeline, durationSeconds);
    if (timelineError) {
      throw new Error(`Invalid seeded timeline for "${definition.title}": ${timelineError}`);
    }
    const validationError = new Track(trackData).validateSync();
    if (validationError) {
      throw new Error(`Invalid seeded track "${definition.title}": ${validationError.message}`);
    }

    return {
      audioSourcePath,
      coverSourcePath,
      audioFileName,
      coverFileName,
      trackData,
      audioFormat,
    };
  });
}

