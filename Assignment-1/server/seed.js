async function seedAssetTracks(seedTracks) {
  let createdCount = 0;
  let updatedCount = 0;
  const legacySeedTracks = [
    { title: 'Besabriyaan', artist: 'Armaan Malik', replacement: seedTracks[0].trackData },
    { title: 'Main Kisi Aur Ka', artist: 'Jubin Nautiyal', replacement: seedTracks[1].trackData },
    { title: 'Humnava Mere', artist: 'Jubin Nautiyal', replacement: seedTracks[2].trackData },
    { title: 'Lo Safar', artist: 'Jubin Nautiyal', replacement: seedTracks[3].trackData },
    {
      title: 'Tum Se',
      artist: 'Sachin-Jigar, Varun Jain, Raghav Chaitanya',
      replacement: seedTracks[4].trackData,
    },
  ];

  for (const legacy of legacySeedTracks) {
    await Track.updateOne(
      { title: legacy.title, artist: legacy.artist },
      { $set: legacy.replacement },
      { runValidators: true }
    );
  }

  for (const { trackData } of seedTracks) {
    const result = await Track.updateOne(
      { title: trackData.title, artist: trackData.artist },
      { $set: trackData },
      { upsert: true, runValidators: true }
    );
    if (result.upsertedCount) createdCount += 1;
    else updatedCount += 1;
  }
  return { createdCount, updatedCount };
}

async function seedDatabase() {
  if (!process.env.MONGO_URI) {
    throw new Error('MONGO_URI must be configured before running the seed script.');
  }

  const assetTracks = loadAssetTracks();
  await mongoose.connect(process.env.MONGO_URI);
  console.log('Connected to MongoDB');

  copySeedAssets(assetTracks);
  const createdUsers = await ensureDevelopmentUsers();
  const seededTracks = await seedAssetTracks(assetTracks);
  console.log(`Created ${createdUsers} missing development accounts.`);
  console.log(`Seeded ${seededTracks.createdCount} new asset tracks and refreshed ${seededTracks.updatedCount} existing asset tracks.`);

  if (createdUsers) {
    console.log('Set DEMO_HOST_PASSWORD, DEMO_LISTENER_PASSWORD, and DEMO_ADMIN_PASSWORD in the local server/.env to sign in.');
  }
}

